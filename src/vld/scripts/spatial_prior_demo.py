"""Benchmark the spatial prior: ridge vs Laplacian-penalised substrate recovery, against planted truth.

Runs entirely on the shipped sample cohort (``voxel_data_sample/voxel_ds.npz``) with deficits generated by
:func:`vld.deficits.make_aphasia_like_deficits`, so every number is reproducible with no extra data.

The point it establishes: ordinary ridge is the *best* of these estimators at held-out prediction and the
*worst* at recovering the substrate, so tuning a lesion-deficit model on prediction picks a worse map. A
graph-Laplacian penalty at a fixed ``beta`` fixes most of that gap without any tuning.

    python -m vld.scripts.spatial_prior_demo                 # default: 3 substrates x 2 noise levels
    python -m vld.scripts.spatial_prior_demo --betas 0,30,100,300 --seeds 5
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from vld.deficits import make_aphasia_like_deficits
from vld.metrics import dice_at_k, morans_i, support_auc
from vld.priors import LaplacianInverse, voxel_adjacency

DEFAULT_DATA = Path(__file__).resolve().parents[3] / "voxel_data_sample" / "voxel_ds.npz"


def _oof_rho(solver: LaplacianInverse, y: np.ndarray, n_folds: int, seed: int) -> float:
    """Out-of-fold Pearson correlation of the map's predicted overlap against the deficit."""
    n = solver.n_patients
    folds = np.array_split(np.random.default_rng(seed).permutation(n), n_folds)
    pred = np.zeros(n, dtype=np.float64)
    for fold in folds:
        train = np.setdiff1d(np.arange(n), fold)
        pred[fold] = solver.X[fold] @ solver.fit(y[train], rows=train)
    target = y - y.mean()
    if pred.std() == 0.0 or target.std() == 0.0:
        return 0.0
    return float(np.corrcoef(pred, target)[0, 1])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", type=Path, default=DEFAULT_DATA)
    ap.add_argument("--betas", type=str, default="0,10,30,100,300",
                    help="comma-separated smoothness weights; 0 is ordinary ridge")
    ap.add_argument("--noise", type=str, default="0.6,1.2", help="comma-separated deficit noise SDs")
    ap.add_argument("--seeds", type=int, default=4)
    ap.add_argument("--n-substrates", type=int, default=3)
    args = ap.parse_args()

    d = np.load(args.data, allow_pickle=True)
    X = d["X"].astype(np.float64)
    mask_idx = d["mask_idx"]
    vol_shape = tuple(int(s) for s in d["vol_shape"])
    centroids = d["centroids"].astype(np.float64)
    names = [str(s) for s in d["substrate_names"]][: args.n_substrates]
    masks = d["substrate_masks"].astype(np.float64)[: args.n_substrates]
    betas = [float(b) for b in args.betas.split(",")]
    noises = [float(v) for v in args.noise.split(",")]
    adjacency = voxel_adjacency(mask_idx, vol_shape)

    volume = X.sum(axis=1)
    cov = np.column_stack([(volume - volume.mean()) / volume.std()])  # volume acts as the confounder
    solvers = {b: LaplacianInverse(X, mask_idx=mask_idx, vol_shape=vol_shape, beta=b, cov=cov)
               for b in betas}

    print(f"cohort: N={X.shape[0]} voxels={X.shape[1]}  substrates={names}")
    print(f"{'substrate':<26}{'noise':>6}{'estimator':>16}{'supportAUC':>12}{'Dice@k':>9}"
          f"{'Moran I':>9}{'OOF rho':>9}")
    for name, mask in zip(names, masks):
        for noise in noises:
            rows: dict[float, list[tuple[float, float, float, float]]] = {b: [] for b in betas}
            for seed in range(args.seeds):
                _, severity, _ = make_aphasia_like_deficits(
                    X, mask, centroids, cov, burden_weight=2.0, noise_sd=noise, seed=seed)
                for beta in betas:
                    w = solvers[beta].fit(severity)
                    sign = np.sign(np.corrcoef(w, mask)[0, 1] + 1e-12)
                    w = sign * w
                    rows[beta].append((support_auc(w, mask),
                                       dice_at_k(w, mask, int(mask.sum())),
                                       morans_i(w, adjacency),
                                       _oof_rho(solvers[beta], severity, 5, seed)))
            for beta in betas:
                m = np.nanmean(rows[beta], axis=0)
                label = "ridge (beta=0)" if beta == 0.0 else f"Laplacian b={beta:g}"
                print(f"{name[:26]:<26}{noise:>6g}{label:>16}{m[0]:>12.3f}{m[1]:>9.3f}"
                      f"{m[2]:>9.3f}{m[3]:>9.3f}")
        print()


if __name__ == "__main__":
    main()
